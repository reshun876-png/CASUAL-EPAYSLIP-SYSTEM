// Helper to construct payslip
export function buildPayslipForStaff(
  staff: TemporalStaff,
  cycle: PayrollCycle,
  shifts: { normalDaysWorked: number; nightShiftsWorked: number; emergencyCallsWorked: number; holidayOrWeekendShifts: number },
  serialIndex: number
): Payslip {
  const customAllowances: { description: string; amount: number }[] = [];
  // Add clinical risk allowance for clinical staff
  if (['Emergency & Casualty', 'Labour Ward & Maternity', 'Clinical Laboratory'].includes(staff.department)) {
    customAllowances.push({
      description: 'Clinical Infection & Risk Subsidy',
      amount: 150,
    });
  }
  // Transport allowance
  customAllowances.push({
    description: 'Local Commuting & Transport Subsidy',
    amount: 100,
  });

  const pay = computeTemporalStaffPay(staff, shifts, customAllowances, []);
  const serialNo = `EH-PS-${cycle.id}-${String(serialIndex).padStart(4, '0')}`;
  const verificationCode = `VRF-${Math.floor(100000 + Math.random() * 900000)}`;

  const bankOrMomo =
    staff.paymentMethod === 'Bank Account'
      ? `${staff.bankName} (Acc: ${staff.accountNumber})`
      : `${staff.paymentMethod} (No: ${staff.momoNumber})`;

  const securityHash = generateSecurityHash({
    serialNo,
    staffId: staff.staffId,
    month: cycle.monthYear,
    netPay: pay.netPay,
    ghanaCard: staff.ghanaCardNo,
  });

  return {
    id: `ps-${cycle.id}-${staff.id}`,
    payslipSerialNo: serialNo,
    staffId: staff.staffId,
    payrollCycleId: cycle.id,
    monthYear: cycle.monthYear,
    periodStart: cycle.periodStart,
    periodEnd: cycle.periodEnd,
    paymentDate: cycle.paymentDate,
    staffName: staff.fullName,
    cadre: staff.cadre,
    department: staff.department,
    ghanaCardNo: staff.ghanaCardNo,
    ssnitNo: staff.ssnitNo,
    paymentMethod: staff.paymentMethod,
    bankOrMomoDetails: bankOrMomo,
    shifts,
    earnings: pay.earnings,
    deductions: pay.deductions,
    grossPay: pay.grossPay,
    totalTaxable: pay.totalTaxable,
    graTaxDeduction: pay.graTaxDeduction,
    ssnitEmployeeDeduction: pay.ssnitEmployeeDeduction,
    welfareDeduction: pay.welfareDeduction,
    otherDeductions: pay.otherDeductions,
    totalDeductions: pay.totalDeductions,
    netPay: pay.netPay,
    ytdGross: Math.round(pay.grossPay * 10 * 100) / 100,
    ytdTax: Math.round(pay.graTaxDeduction * 10 * 100) / 100,
    ytdNet: Math.round(pay.netPay * 10 * 100) / 100,
    securityHash,
    verificationCode,
    generatedAt: '2026-10-27T10:30:00Z',
    generatedBy: 'Mrs. Faustina Baidoo (HR & Payroll Officer)',
    isLocked: true,
    isApproved: true,
    notes: 'Essikado Hospital Temporal Staff Monthly Payroll - Certified for payment.',
  };
}

